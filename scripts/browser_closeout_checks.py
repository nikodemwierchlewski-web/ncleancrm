"""Historical closeout: explicit missing-photo reasons, never fake cancellation."""
from playwright.sync_api import expect


def verify_historical_closeout(page, base, output):
    day = '2026-10-10'
    page.goto(base + '/calendar?day=' + day + '&add=true')
    form = page.locator('#booking-form')
    form.locator('[data-category-choice="1"]').click()
    form.locator('[name=qty_2]').fill('1')
    form.locator('[name=historical]').check()
    expect(form.locator('[name=day]')).to_have_value(day)
    form.get_by_role('button', name='Zapisz zlecenie', exact=True).click()
    expect(page.locator('#booking-editor')).not_to_be_visible()
    booking = page.locator('#agenda-orders [data-order]').filter(has_text='Klient nieustalony').last.get_attribute('data-order')
    page.goto(base + '/work/' + booking)
    form = page.locator('#complete-form')
    expect(form.locator('.photo-exceptions')).to_have_attribute('open', 'open')
    expect(form.locator('[name=before_exception]')).to_be_visible()
    expect(form.locator('[name=after_exception]')).to_be_visible()
    expect(form).to_contain_text('Dawna realizacja: możesz wyjaśnić brak archiwalnych zdjęć.')
    assert form.locator('[data-completion-photos]').bounding_box()['height'] >= 44
    form.locator('[data-completion-photos]').click()
    assert page.locator('#photos').evaluate('e=>e.open')
    for width in (360, 390, 768, 1440):
        page.set_viewport_size({'width': width, 'height': 844})
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        page.screenshot(path=str(output / ('historical-closeout-' + str(width) + '.png')), full_page=True)
    form.locator('[name=final_total]').fill('240')
    form.locator('[name=chem_0]').select_option('ZERO')
    form.locator('[name=no_notes]').check()
    form.get_by_role('button', name='Zapisz wykonanie', exact=True).click()
    expect(page).to_have_url(base + '/work/' + booking + '?saved=1')
    expect(page.locator('.visit-meta')).to_contain_text('Wykonane')
    page.goto(base + '/day-closeout?date=' + day + '&order=' + booking)
    expect(page.locator('.closeout-missing')).to_contain_text('zdjęcie przed, zdjęcie po')
    page.locator('.closeout-missing a').click()
    expect(page.locator('#complete-form [name=before_exception]')).to_be_visible()
    assert page.locator('.closeout-missing a').bounding_box()['height'] >= 44
    finish = page.locator('.day-finish')
    finish.get_by_role('button', name='Zamknij dzień', exact=True).click()
    expect(finish.locator('.review-error')).to_contain_text('zdjęcie przed')
    form = page.locator('#complete-form')
    expect(form.locator('[name=final_total]')).to_have_value('240.00')
    form.locator('[name=before_exception]').fill('Nie zachowało się archiwalne zdjęcie przed usługą')
    form.get_by_role('button', name='Zapisz i następne', exact=True).click()
    expect(page.locator('.closeout-missing')).to_contain_text('zdjęcie po')
    expect(page.locator('.closeout-missing')).not_to_contain_text('zdjęcie przed')
    form = page.locator('#complete-form')
    form.locator('[name=after_exception]').fill('Nie zachowało się archiwalne zdjęcie po usłudze')
    form.get_by_role('button', name='Zapisz i następne', exact=True).click()
    expect(page.locator('.closeout-missing')).to_have_count(0)
    page.locator('.day-finish').get_by_role('button', name='Zamknij dzień', exact=True).click()
    expect(page.locator('.day-finish').get_by_role('button', name='Dzień zamknięty ✓', exact=True)).to_be_disabled()
    page.reload()
    expect(page.locator('.day-finish').get_by_role('button', name='Dzień zamknięty ✓', exact=True)).to_be_disabled()
    expect(page.locator('[name=before_exception]')).to_have_value('Nie zachowało się archiwalne zdjęcie przed usługą')
    expect(page.locator('[name=after_exception]')).to_have_value('Nie zachowało się archiwalne zdjęcie po usłudze')
    print('PASS historical 2026-10-10: visible photo reasons, upload link, partial DONE save, explicit closure errors, both reasons saved, closed day after reload; four widths.', flush=True)
